"""Generate the torrc of anonimo's own Tor instance. GPL-3.0-or-later."""

import os

from paths import DEFAULT, DNS_PORT, OBFS4PROXY, ONION_NET, SNOWFLAKE_CLIENT, TRANS_PORT

TRANSPORTS = {'obfs4': OBFS4PROXY, 'snowflake': SNOWFLAKE_CLIENT}
TRANSPORT_MISSING = {'obfs4': 'The obfs4 bridge program is not installed',
                     'snowflake': 'The snowflake bridge program is not installed'}
NO_LINES = {'obfs4': 'No obfs4 bridge lines available',
            'snowflake': 'No snowflake bridge lines available'}


class TorrcError(ValueError):
    pass


def transport_available(kind, exists=os.path.exists):
    if kind == 'none':
        return True
    return kind in TRANSPORTS and bool(exists(TRANSPORTS[kind]))


def read_bridge_file(path):
    """Bridge lines of a file, without blank and comment lines."""
    try:
        with open(path, encoding='utf-8') as handle:
            return [line.strip() for line in handle
                    if line.strip() and not line.lstrip().startswith('#')]
    except FileNotFoundError:
        return []


def build_torrc(bridges, obfs4_lines=(), snowflake_lines=(), exists=os.path.exists):
    if bridges not in ('none', 'obfs4', 'snowflake'):
        raise TorrcError('Unknown bridge type')
    lines = [
        '# Generated by syslinuxos-anonimo. Do not edit: it is rewritten at every start.',
        f'DataDirectory {DEFAULT.data_dir}',
        f'ControlSocket {DEFAULT.control_socket}',
        'CookieAuthentication 1',
        f'CookieAuthFile {DEFAULT.cookie}',
        'SocksPort 0',
        f'TransPort 127.0.0.1:{TRANS_PORT}',
        f'DNSPort 127.0.0.1:{DNS_PORT}',
        'AutomapHostsOnResolve 1',
        'AutomapHostsSuffixes .onion',
        f'VirtualAddrNetworkIPv4 {ONION_NET}',
        'Log notice syslog',
    ]
    if bridges != 'none':
        if not transport_available(bridges, exists):
            raise TorrcError(TRANSPORT_MISSING[bridges])
        source = obfs4_lines if bridges == 'obfs4' else snowflake_lines
        selected = [line for line in source if line.split()[:1] == [bridges]]
        if not selected:
            raise TorrcError(NO_LINES[bridges])
        lines += ['UseBridges 1', f'ClientTransportPlugin {bridges} exec {TRANSPORTS[bridges]}']
        lines += [f'Bridge {line}' for line in selected]
    return '\n'.join(lines) + '\n'
